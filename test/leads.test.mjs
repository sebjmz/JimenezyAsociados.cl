// Leads del sitio público (tasación / popup): creación sin sesión validada por reglas.
import { initializeTestEnvironment, assertSucceeds, assertFails } from '@firebase/rules-unit-testing';
import { doc, getDoc, getDocs, addDoc, updateDoc, deleteDoc, collection, serverTimestamp } from 'firebase/firestore';
import fs from 'fs';
const C='artifacts/jimenez-portal-oficial/leads_web';
const env=await initializeTestEnvironment({projectId:'demo-leads',firestore:{rules:fs.readFileSync(process.env.RULES,'utf8'),host:'127.0.0.1',port:8080}});
const anon=env.unauthenticatedContext().firestore();
const partner=env.authenticatedContext('p1',{email:'p1@x.cl'}).firestore();
const admin=env.authenticatedContext('seb',{email:'sebjmz@gmail.com'}).firestore();
let ok=0,bad=0;const t=async(n,p)=>{try{await p;console.log('PASS',n);ok++}catch(e){console.log('FAIL',n,e.message);bad++}};
const base=()=>({origen:'tasacion',nombre:'Nombre',telefono:'+56912345678',consentimiento:true,consentimientoTexto:'Acepto',pagina:'/tasacion.html',createdAt:serverTimestamp(),datos:{tipo:'casa',valorComercialUF:'4500'}});
let id;
await t('anónimo crea lead de tasación válido', assertSucceeds((async()=>{id=(await addDoc(collection(anon,C),base())).id;})()));
await t('anónimo crea lead popup solo con email', assertSucceeds(addDoc(collection(anon,C),{origen:'popup-index',email:'a@b.cl',consentimiento:true,createdAt:serverTimestamp()})));
await t('NO sin consentimiento', assertFails(addDoc(collection(anon,C),{...base(),consentimiento:false})));
await t('NO sin campo consentimiento', assertFails((async()=>{const d=base();delete d.consentimiento;await addDoc(collection(anon,C),d);})()));
await t('NO sin teléfono ni email', assertFails((async()=>{const d=base();delete d.telefono;await addDoc(collection(anon,C),d);})()));
await t('NO origen desconocido', assertFails(addDoc(collection(anon,C),{...base(),origen:'spam'})));
await t('NO campos extra', assertFails(addDoc(collection(anon,C),{...base(),admin:true})));
await t('NO fecha falsa', assertFails(addDoc(collection(anon,C),{...base(),createdAt:new Date(2000,0,1)})));
await t('NO email inválido', assertFails(addDoc(collection(anon,C),{...base(),email:'no-es-email'})));
await t('NO nombre gigante', assertFails(addDoc(collection(anon,C),{...base(),nombre:'x'.repeat(81)})));
await t('NO teléfono corto', assertFails(addDoc(collection(anon,C),{...base(),telefono:'123'})));
await t('NO datos con >20 claves', assertFails(addDoc(collection(anon,C),{...base(),datos:Object.fromEntries(Array.from({length:21},(_,i)=>['k'+i,'v']))})));
await t('anónimo NO lee leads', assertFails(getDocs(collection(anon,C))));
await t('anónimo NO lee su propio lead', assertFails(getDoc(doc(anon,`${C}/${id}`))));
await t('partner NO lee leads', assertFails(getDocs(collection(partner,C))));
await t('anónimo NO modifica lead', assertFails(updateDoc(doc(anon,`${C}/${id}`),{nombre:'x'})));
await t('anónimo NO borra lead', assertFails(deleteDoc(doc(anon,`${C}/${id}`))));
await t('admin lee leads', assertSucceeds(getDocs(collection(admin,C))));
console.log(`\nRESULTADO: ${ok} PASS, ${bad} FAIL`);await env.cleanup();process.exit(bad?1:0);
